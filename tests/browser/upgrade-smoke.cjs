/* Opt-in upgrade checks with a synthetic PDF and a fake provider, never external calls. */
const {chromium} = require('playwright-core');
const assert = require('assert');
(async () => {
  const base = process.env.UPGRADE_TEST_URL, source = process.env.UPGRADE_TEST_PDF;
  const teacher = JSON.parse(process.env.UPGRADE_TEST_TEACHER);
  const args = ['--no-sandbox', '--disable-dev-shm-usage'];
  if (process.env.CHROMIUM_SINGLE_PROCESS === '1') args.push('--single-process', '--no-zygote');
  const browser = await chromium.launch({executablePath: process.env.CHROMIUM_PATH, headless: true, args});
  const context = await browser.newContext({viewport: {width:390, height:844}});
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  const noOverflow = async stage => {
    const {scroll, viewport} = await page.evaluate(() => ({scroll: document.documentElement.scrollWidth, viewport: document.documentElement.clientWidth}));
    assert(scroll <= viewport, `${stage} overflows mobile viewport: ${scroll} > ${viewport}`);
  };
  try {
    const tag = 'upgrade_' + Date.now();
    await page.goto(base+'/auth/register/');
    for (const [field,value] of Object.entries({first_name:'Arena',last_name:'Upgrade',username:tag,email:tag+'@example.test',password:'PracticeBrowserPass987!',confirm_password:'PracticeBrowserPass987!'})) await page.locator('#id_'+field).fill(value);
    await Promise.all([page.waitForURL('**/dashboard/**'), page.locator('form').filter({has:page.locator('#id_username')}).locator('button[type=submit]').click()]);
    await page.goto(base+'/questions/practice/upload/');
    await page.locator('#id_title').fill('Structured browser paper');
    await page.locator('#id_pdf_file').setInputFiles(source);
    await Promise.all([page.waitForURL('**/settings/'), page.getByRole('button',{name:/Upload & extract/i}).click()]);
    assert.strictEqual(await page.locator('table.question-table').count(), 1, 'Extracted table missing');
    assert.strictEqual(await page.locator('table.question-table th').first().getAttribute('colspan'), '2');
    await noOverflow('table review');
    await page.locator('.ai-batch-select input').nth(1).check();
    await page.locator('.ai-batch-select input').nth(2).check();
    await page.locator('#ai-batch-panel summary').click();
    await page.locator('#batch-consent').check();
    await page.getByRole('button',{name:'Request selected suggestions'}).click();
    await page.getByText('Finished 2 requests.', {exact:false}).waitFor();
    assert.strictEqual(await page.getByText('· suggested').count(), 2);
    await page.getByRole('link',{name:'AI answer review'}).first().click();
    assert(await page.getByText('AI can suggest. Only you can confirm.').isVisible());
    assert.strictEqual(await page.locator('#ai-consent').isChecked(), false);
    assert.strictEqual(await page.locator('#send-vision').isChecked(), false);
    // HTML validation blocks an unconsented request; the server also enforces it.
    await page.getByRole('button',{name:'Request AI suggestion'}).click();
    assert(await page.locator('#ai-consent:invalid').count());
    await page.locator('#ai-consent').check();
    await Promise.all([page.waitForURL('**/ai/'), page.getByRole('button',{name:'Request AI suggestion'}).click()]);
    assert(await page.getByText('AI suggested option').isVisible());
    assert(await page.getByText('No confirmed key · ungraded').isVisible());
    await page.locator('#confirmed-answer').selectOption('B');
    await page.locator('#confirmed-explanation').fill('Reviewed and edited by a person.');
    await page.locator('#human-confirm').check();
    await Promise.all([page.waitForURL('**/ai/'), page.getByRole('button',{name:'Confirm selected answer'}).click()]);
    assert(await page.getByText('Current confirmed key: B').isVisible());
    await noOverflow('AI review');

    await page.getByRole('link',{name:'← Edit question'}).click();
    await page.getByText('Compare original question excerpts').click();
    await page.locator('img[alt^="Original question"]').first().waitFor({state:'visible'});
    await page.waitForFunction(() => document.querySelector('img[alt^="Original question"]').naturalWidth > 0);
    await page.getByRole('textbox',{name:'Table 1, row 3, cell 2'}).fill('$\\frac{1}{2}$');
    await page.getByRole('button',{name:'Add row'}).click();
    await page.getByRole('textbox',{name:'Table 1, row 4, cell 1'}).fill('Reviewed row');
    await page.getByRole('textbox',{name:'Table 1, row 4, cell 2'}).fill('समय');
    if (await page.locator('#id_reviewed').count()) await page.locator('#id_reviewed').check();
    await noOverflow('table editor');
    await Promise.all([page.waitForURL('**/settings/'),page.getByRole('button',{name:'Save question'}).click()]);
    assert(await page.locator('table.question-table').getByText('Reviewed row').isVisible());
    assert(await page.locator('table.question-table .katex').count(), 'Math in table did not render');
    await page.locator('#id_duration_minutes').fill('30');
    if (await page.locator('#id_acknowledge_review').count()) await page.locator('#id_acknowledge_review').check();
    if (await page.locator('#id_acknowledge_unassigned').count()) await page.locator('#id_acknowledge_unassigned').check();
    await Promise.all([page.waitForURL('**/instructions/'), page.getByRole('button',{name:'Create private test'}).click()]);
    await page.locator('#declaration-check').check();
    await Promise.all([page.waitForURL('**/session/**'),page.locator('#start-btn').click()]);
    assert(await page.locator('table.question-table').getByText('Reviewed row').isVisible(), 'Table did not reach CBT');
    assert(await page.locator('table.question-table .katex').count(), 'CBT table math did not render');
    const payload = await page.locator('#questions-data').textContent();
    assert(!payload.includes('is_correct') && !payload.includes('Reviewed and edited by a person'), 'Answer data leaked into CBT');
    await noOverflow('CBT');
    await page.locator('.option-card').filter({hasText:'Second'}).click();
    await page.locator('#btn-open-submit-modal').click(); await page.locator('#btn-confirm-submit').click();
    await page.waitForURL('**/completed/'); await page.getByRole('link',{name:'Review my answers'}).click();
    assert(await page.getByText('1 / 3 attempted').isVisible());
    assert(await page.locator('table.question-table').getByText('Reviewed row').isVisible());
    assert(await page.getByText('Reviewed and edited by a person.').isVisible());
    await noOverflow('result');
    console.log('PASS student: table editor, source, mocked consent/confirmation, CBT, result');

    await context.clearCookies();
    await page.goto(base+'/auth/login/');
    await page.locator('#id_username').fill(teacher.username); await page.locator('#id_password').fill(teacher.password);
    await Promise.all([page.waitForURL('**/dashboard/**'),page.locator('button[type=submit]').click()]);
    await page.goto(base+teacher.review);
    assert(await page.locator('table.question-table').getByText('Teacher header').isVisible());
    await page.locator('.ai-batch-select input').first().check();
    await page.locator('#ai-batch-panel summary').click();
    await page.locator('#batch-consent').check();
    await page.getByRole('button',{name:'Request selected suggestions'}).click();
    await page.getByText('Finished 1 request.', {exact:false}).waitFor();
    await page.goto(base+teacher.edit);
    assert(await page.getByRole('textbox',{name:'Table 1, row 2, cell 1'}).isVisible());
    await page.goto(base+teacher.ai);
    assert(await page.getByText('AI can suggest. Only you can confirm.').isVisible());
    await noOverflow('teacher AI');
    if (errors.length) throw new Error('Browser errors: '+JSON.stringify(errors));
    console.log('BROWSER_UPGRADE_OK');
  } finally { await context.close(); await browser.close(); }
})().catch(error => { console.error('BROWSER_UPGRADE_FAILED',error); process.exitCode = 1; });
